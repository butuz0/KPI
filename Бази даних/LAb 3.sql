SELECT * FROM Платіжне_доручення WHERE Дата = '2022-02-24'

--b.	Операторів порівняння

SELECT * FROM Регіональне_казначейство WHERE Кількість_бюджетних_установ > 100

--c.	Умов з використанням логічних операторів AND, OR та NOT.

SELECT * FROM Працівник_казначейства
WHERE Зарплата > 20000 AND Зарплата < 30000

SELECT * FROM Бюджетна_установа
WHERE Кількість_працівників > 200 OR Бюджет > 1000000000

SELECT * FROM Регіональне_казначейство
WHERE NOT Кількість_працівників > Кількість_бюджетних_установ

--d.	Умов з використанням комбінацій логічних операторів

SELECT * FROM Працівник_казначейства
WHERE Зарплата < 15000 AND (Казначейство = 'РГККВ01' OR Казначейство = 'РГККВОБЛ01')

--e.	З використанням виразів над стовпцями, як в якості новостворених стовпців, так і умовах
