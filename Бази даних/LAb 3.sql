--2)	Створити запити з використанням підзапитів та з’єднань (разом 11 запитів) (в запитах повинні використовуватись 2 та більше таблиць):

--a.	Використання підзапитів в рядку вибірки полів (у секції select) та вибірки з таблиць (у секції from)

SELECT ID, Кількість_працівників, (
SELECT SUM(Зарплата) FROM Працівник_казначейства WHERE Казначейство = Регіональне_казначейство.ID)
FROM Регіональне_казначейство

--b.	Використання підзапитів в умовах з конструкціями EXISTS, IN

SELECT ID, Назва, Бюджет, Комерційний_банк FROM Бюджетна_установа AS ПБК_Бюджетні_установи
WHERE Бюджет > 50000000 AND EXISTS (SELECT ID FROM Комерційний_банк WHERE ID = 'ПБК' AND ID = ПБК_Бюджетні_установи.Комерційний_банк)

SELECT * FROM Працівник_казначейства
WHERE Казначейство IN (SELECT ID FROM Регіональне_казначейство WHERE Кількість_працівників < 25)

--c.	Декартовий добуток

SELECT Кошторис.ID AS 'Кошторис', КЕКВ.ID AS 'КЕКВи'
FROM Кошторис CROSS JOIN КЕКВ

--d.	З’єднання декількох таблиць за рівністю

SELECT * FROM Платіжне_доручення, Бюджетна_установа
WHERE Платіжне_доручення.Бюджетна_установа = Бюджетна_установа.ID
 
--e.	З’єднання декількох таблиць за рівністю та умовою відбору

SELECT * FROM Платіжне_доручення, Бюджетна_установа
WHERE Платіжне_доручення.Бюджетна_установа = Бюджетна_установа.ID AND Платіжне_доручення.Cума > Бюджетна_установа.Бюджет/20


--f.	Внутрішнього з’єднання

SELECT * FROM КЕКВ
INNER JOIN Платіжне_доручення ON Платіжне_доручення.Підстава =
КЕКВ.Призначення

--g.	Лівого зовнішнього з’єднання

SELECT * FROM Регіональне_казначейство
LEFT OUTER JOIN Бюджетна_установа ON Бюджетна_установа.Казначейство =
Регіональне_казначейство.ID

--h.	Правого зовнішнього з’єднання

SELECT * FROM Бюджетна_установа
RIGHT OUTER JOIN Комерційний_банк ON Бюджетна_установа.Комерційний_банк =
Комерційний_банк.ID

--i.	Об’єднання запитів

SELECT Казначейство, Назва FROM Бюджетна_установа
UNION
SELECT ID, Регіон FROM Регіональне_казначейство
WHERE ID = Регіональне_казначейство.ID
ORDER BY Назва
